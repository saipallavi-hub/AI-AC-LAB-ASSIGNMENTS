"""**Task 4: Real-Time Application: Ride-Sharing Data Cleaning**
Scenario:
A ride-sharing company has trip data with errors.
Requirements:
• Standardize pickup and drop locations
• Fill missing fare amounts with median values
• Remove duplicate ride entries
• Normalize driver ratings
• Generate a summary of data improvements
Expected Output:
A clean dataset ready for operational analysis.
"""
import pandas as pd
import numpy as np

data_rides = {
    'ride_id':[1001,1002,1003,1004,1005,1006,1007,1008,1009,1010],
    'pickup_location':[' Downtown ','Airport','Suburb A','Downtown',' City Center','Airport','Suburb B','Downtown','City Center ','Suburb A'],
    'dropoff_location':['Uptown',' City Center','Downtown','Suburb A','Airport ','Suburb B','Uptown','Airport','Downtown','City Center'],
    'fare_amount':[25.5,45,np.nan,20,30.75,48.2,15,np.nan,22,35.5],
    'driver_rating':[4.8,3.5,5.0,4.2,np.nan,4.9,3.0,4.5,4.0,5.0],
    'ride_timestamp':[
        '2023-01-01 10:00:00','2023-01-01 10:15:00','2023-01-01 10:30:00',
        '2023-01-01 10:45:00','2023-01-01 11:00:00','2023-01-01 10:15:00',
        '2023-01-01 11:30:00','2023-01-01 11:45:00','2023-01-01 12:00:00',
        '2023-01-01 12:15:00']
}

df_rides = pd.DataFrame(data_rides)

# Clean text
df_rides['pickup_location'] = df_rides['pickup_location'].str.strip().str.lower()
df_rides['dropoff_location'] = df_rides['dropoff_location'].str.strip().str.lower()

# Fill missing fare
df_rides['fare_amount'].fillna(df_rides['fare_amount'].median(), inplace=True)

# Remove duplicates
df_rides.drop_duplicates(subset=['ride_id','ride_timestamp'], inplace=True)

# Normalize ratings
df_rides['driver_rating'] = df_rides['driver_rating'].fillna(
    df_rides['driver_rating'].median()
)

df_rides['normalized_rating'] = (
    (df_rides['driver_rating'] - df_rides['driver_rating'].min())/
    (df_rides['driver_rating'].max() - df_rides['driver_rating'].min())
)

print("Cleaned Ride Dataset")
print(df_rides.head())

